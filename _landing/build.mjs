#!/usr/bin/env node
// Builds the root index.html (the labs.vossers.com landing page).
//
// Every top-level folder that contains an index.html is listed, unless its
// name starts with "." or "_", or it appears in "hidden" in projects.json.
// Title, one-liner and group come from projects.json; a folder with no entry
// there falls back to its own <title> and meta description, under "Other".
//
// Usage: node _landing/build.mjs

import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const config = JSON.parse(readFileSync(join(here, "projects.json"), "utf8"));
const hidden = new Set(config.hidden ?? []);
const meta = config.projects ?? {};
const FALLBACK_GROUP = "Other";

const decode = s => s
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n))
  .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
  .replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'")
  .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
const esc = s => s.replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

function fromHtml(dir) {
  const html = readFileSync(join(root, dir, "index.html"), "utf8");
  const title = html.match(/<title[^>]*>([^<]*)<\/title>/i)?.[1].trim();
  const desc = html.match(/<meta\s+name=["']description["']\s+content=["']([^"']*)["']/i)?.[1].trim();
  return { title: title ? decode(title) : dir, description: desc ? decode(desc) : "" };
}

const projects = readdirSync(root, { withFileTypes: true })
  .filter(d => d.isDirectory() && !/^[._]/.test(d.name) && !hidden.has(d.name))
  .filter(d => existsSync(join(root, d.name, "index.html")))
  .map(d => {
    const m = meta[d.name] ?? {};
    const scraped = m.title && m.description ? {} : fromHtml(d.name);
    return {
      dir: d.name,
      title: m.title ?? scraped.title,
      description: m.description ?? scraped.description,
      group: m.group ?? FALLBACK_GROUP,
    };
  })
  .sort((a, b) => a.title.localeCompare(b.title, "en", { sensitivity: "base" }));

const order = [...(config.groups ?? [])];
for (const p of projects) if (!order.includes(p.group)) order.push(p.group);

const sections = order
  .map(g => [g, projects.filter(p => p.group === g)])
  .filter(([, items]) => items.length)
  .map(([g, items]) => `
    <section>
      <h2>${esc(g)} <span>${items.length}</span></h2>
      <div class="grid">${items.map(p => `
        <a class="card" href="${encodeURIComponent(p.dir)}/">
          <h3>${esc(p.title)}</h3>
          ${p.description ? `<p>${esc(p.description)}</p>` : ""}
        </a>`).join("")}
      </div>
    </section>`).join("\n");

const page = `<!DOCTYPE html>
<!-- Generated by _landing/build.mjs from _landing/projects.json. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Labs</title>
<meta name="description" content="Small apps, games and explainers, kept in one place.">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Source+Serif+4:opsz,wght@8..60,600&display=swap">
<style>
  :root {
    --bg: #f6f6f3; --panel: #fff; --fg: #1d1f1e; --muted: #6a6e6b; --line: #e3e3dd; --accent: #2f5d50;
    --sans: system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
    --serif: "Source Serif 4", Georgia, "Times New Roman", serif;
    color-scheme: light dark;
  }
  @media (prefers-color-scheme: dark) {
    :root { --bg: #141615; --panel: #1c1f1e; --fg: #e9eae6; --muted: #9a9f9b; --line: #2c302e; --accent: #8cc2b2; }
  }
  * { box-sizing: border-box; }
  body { margin: 0; background: var(--bg); color: var(--fg); font: 15px/1.5 var(--sans); }
  main { max-width: 1040px; margin: 0 auto; padding: 56px max(16px, env(safe-area-inset-right)) 72px max(16px, env(safe-area-inset-left)); display: grid; gap: 36px; }
  a { color: inherit; text-decoration: none; }
  header { border-bottom: 1px solid var(--line); padding-bottom: 20px; }
  h1 { font: 600 32px/1.15 var(--serif); margin: 0 0 8px; }
  header p { margin: 0; color: var(--muted); max-width: 60ch; }
  section { display: grid; gap: 12px; }
  h2 { font: 500 12px var(--sans); text-transform: uppercase; letter-spacing: .08em; color: var(--muted); margin: 0; }
  h2 span { opacity: .7; margin-left: 6px; font-variant-numeric: tabular-nums; }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(min(320px, 100%), 1fr)); gap: 10px; }
  .card { background: var(--panel); border-radius: 6px; padding: 16px 18px; display: grid; align-content: start; gap: 4px;
    box-shadow: 0 0 0 1px var(--line); transition: box-shadow .15s; }
  .card:hover { box-shadow: 0 0 0 1px var(--accent), 0 4px 14px -8px rgba(0,0,0,.25); }
  .card:focus-visible { outline: 2px solid var(--accent); outline-offset: 2px; }
  h3 { font: 600 18px/1.25 var(--serif); margin: 0; }
  .card p { margin: 0; color: var(--muted); font-size: 14px; line-height: 1.45; }
  @media (prefers-reduced-motion: reduce) { .card { transition: none; } }
</style>
</head>
<body>
<main>
  <header>
    <h1>Labs</h1>
    <p>Small apps, games and explainers I've built, kept here so I can find them again. ${projects.length} projects.</p>
  </header>
${sections}
</main>
</body>
</html>
`;

writeFileSync(join(root, "index.html"), page);
console.log(`index.html: ${projects.length} projects listed, ${hidden.size} hidden.`);
