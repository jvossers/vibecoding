// Builds standalone/parity.html: the whole app (markup, styles, code and catalogue) in one
// self-contained HTML file. No server, no fetch(), no external requests: it can be opened
// from disk, attached to an email, or pinned as a tab in Microsoft Teams.
//
//   node scripts/buildStandalone.js           write standalone/parity.html
//   node scripts/buildStandalone.js --check   fail if standalone/parity.html is out of date
//
// To roll out with real data, replace data/products.json and data/instrument-families.json
// with the converted catalogue and run this script again. Nothing else changes.
//
// The bundler is deliberately tiny. It only understands the import/export forms this
// codebase uses (named imports, `export function|const|let|class`) and stops with an error
// on anything else, so it can never produce a silently broken file.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'standalone', 'parity.html');
const ENTRY = join(ROOT, 'js', 'app.js');

// The file may only run its own inline code and styles; it cannot load or send anything.
const CSP = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'";

const read = (p) => readFileSync(p, 'utf8');

// Turns each ES module into a function that returns its exports, in dependency order.
function bundleModules(entry) {
  const modules = new Map(); // absolute path -> wrapped source

  function visit(file) {
    if (modules.has(file)) return;
    modules.set(file, null); // reserve: marks the module as in progress
    let src = read(file);
    const exportsList = [];

    src = src.replace(/^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*$/gm, (_, names, spec) => {
      if (!spec.startsWith('.')) throw new Error(`${rel(file)}: only relative imports are supported (${spec})`);
      const target = resolve(dirname(file), spec);
      visit(target);
      const binding = names.split(',').map((n) => n.trim()).filter(Boolean)
        .map((n) => n.replace(/\s+as\s+/, ': ')).join(', ');
      return `const { ${binding} } = __require(${JSON.stringify(rel(target))});`;
    });

    src = src.replace(/^export\s+((?:async\s+)?function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, name) => {
      exportsList.push(name);
      return `${kind} ${name}`;
    });

    const leftover = src.match(/^\s*(import\s*[{*'\w]|export\s+(default|\{|\*))[^\n]*/m);
    if (leftover) throw new Error(`${rel(file)}: unsupported module syntax: ${leftover[0].trim()}`);

    modules.set(file, `__define(${JSON.stringify(rel(file))}, function () {\n${src}\nreturn { ${exportsList.join(', ')} };\n});`);
  }

  visit(entry);
  return [
    '(function () {',
    '"use strict";',
    'const __factories = new Map(), __cache = new Map();',
    'function __define(id, factory) { __factories.set(id, factory); }',
    'function __require(id) { if (!__cache.has(id)) __cache.set(id, __factories.get(id)()); return __cache.get(id); }',
    ...modules.values(),
    `__require(${JSON.stringify(rel(entry))});`,
    '})();',
  ].join('\n');
}

const rel = (p) => relative(ROOT, p).split('\\').join('/');

// JSON is safe inside <script type="application/json"> once "</" can't close the element.
const embedJson = (value) => JSON.stringify(value).replace(/<\//g, '<\\/').replace(/<!--/g, '<\\!--');
const embedScript = (code) => code.replace(/<\/script/gi, '<\\/script');

export function buildStandalone() {
  const catalogue = {
    products: JSON.parse(read(join(ROOT, 'data', 'products.json'))),
    families: JSON.parse(read(join(ROOT, 'data', 'instrument-families.json'))),
  };
  let html = read(join(ROOT, 'index.html'));

  const replaceOnce = (pattern, replacement, what) => {
    if (!pattern.test(html)) throw new Error(`index.html: could not find ${what}`);
    html = html.replace(pattern, () => replacement);
  };

  replaceOnce(/<meta charset="utf-8">/, `<meta charset="utf-8">\n  <meta http-equiv="Content-Security-Policy" content="${CSP}">`, 'the charset meta');
  replaceOnce(/<link rel="stylesheet" href="css\/styles\.css">/, `<style>\n${read(join(ROOT, 'css', 'styles.css'))}</style>`, 'the stylesheet link');
  replaceOnce(/\s*<noscript>[\s\S]*?<\/noscript>/, '\n  <noscript><p style="padding:24px">Parity needs JavaScript.</p></noscript>', 'the noscript block');
  replaceOnce(/<script type="module" src="js\/app\.js"><\/script>/,
    `<script type="application/json" id="parity-data">${embedJson(catalogue)}</script>\n  <script>\n${embedScript(bundleModules(ENTRY))}\n  </script>`,
    'the app script');

  return `<!-- Parity single-file build. Generated by scripts/buildStandalone.js; do not edit. -->\n${html}`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const html = buildStandalone();
  const kb = (Buffer.byteLength(html) / 1024).toFixed(0);
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = read(OUT); } catch { /* missing */ }
    if (current !== html) {
      console.error(`${rel(OUT)} is out of date. Run: node scripts/buildStandalone.js`);
      process.exit(1);
    }
    console.log(`${rel(OUT)} is up to date (${kb} KB).`);
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, html);
    console.log(`Wrote ${rel(OUT)} (${kb} KB).`);
  }
}
