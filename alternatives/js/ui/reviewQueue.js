// Screen D: prototype review queue.

import { h, clear, debounce, append } from './dom.js';
import { icon, classificationChip, reviewChip, skuTag, emptyState, REVIEW_LABELS } from './components.js';
import { evaluateCandidate, defaultRequirements, CLASSIFICATION_LABELS, pairKey, isEligible } from '../domain/matching.js';

const PAGE = 50;

// Seeded pairs plus pairs reviewed locally from a live search, with their effective status.
export async function reviewQueueItems(ctx) {
  const [seeds, products, families] = await Promise.all([ctx.repo.listAlternativeSeeds(), ctx.repo.listProducts(), ctx.repo.familiesById()]);
  const byId = Object.fromEntries(products.map((p) => [p.id, p]));
  const items = [];
  const seen = new Set();
  for (const seed of seeds) {
    seen.add(pairKey(seed.sourceProductId, seed.candidateProductId));
    items.push({ seed, result: seed, source: byId[seed.sourceProductId], candidate: byId[seed.candidateProductId] });
  }
  for (const pair of ctx.reviews.localPairs()) {
    if (seen.has(pairKey(pair.sourceProductId, pair.candidateProductId))) continue;
    const source = byId[pair.sourceProductId], candidate = byId[pair.candidateProductId];
    if (!source || !candidate) continue;
    items.push({ seed: null, result: evaluateCandidate(source, candidate, defaultRequirements(source), { families }), source, candidate });
  }
  for (const it of items) it.review = ctx.reviews.get(it.source.id, it.candidate.id, it.seed);
  return items;
}

export async function renderReviewQueue(root, ctx, { query }) {
  const state = {
    status: ['pending', 'approved_for_demo', 'rejected'].includes(query.get('status')) ? query.get('status') : 'all',
    cls: query.get('cls') ?? '',
    q: query.get('q') ?? '',
    local: query.get('local') === '1',
    eligible: query.get('eligible') === '1',
    limit: PAGE,
    open: new Set(),
  };
  let items = await reviewQueueItems(ctx);

  const syncUrl = () => {
    const p = new URLSearchParams();
    if (state.status !== 'all') p.set('status', state.status);
    if (state.cls) p.set('cls', state.cls);
    if (state.q) p.set('q', state.q);
    if (state.local) p.set('local', '1');
    if (state.eligible) p.set('eligible', '1');
    ctx.replaceQuery('/review', p);
  };

  append(root, 
    h('div', { class: 'page-head' }, h('div', {},
      h('div', { class: 'eyebrow' }, 'Internal review'),
      h('h1', {}, 'Review queue'),
      h('p', { class: 'lede' }, 'Candidate pairs generated by the demo rules, with any decisions made in this browser. Open a pair to return to its comparison.'))),
    h('div', { class: 'proto-banner', role: 'note' }, icon('shield'),
      h('div', {}, h('strong', {}, 'Prototype-only statuses. '),
        h('p', {}, '“Approved for demo” is an internal UI state for this demonstration. It is not a technical, quality or regulatory approval, and the catalogue is entirely synthetic. Decisions are stored in this browser only; use “Reset demo data” to clear them.'))),
  );

  const tabs = h('div', { class: 'tabs', role: 'tablist', 'aria-label': 'Filter by review status' });
  const clsSel = h('select', { 'aria-label': 'Filter by classification', style: { width: 'auto' } },
    h('option', { value: '' }, 'All classifications'), Object.entries(CLASSIFICATION_LABELS).map(([k, t]) => h('option', { value: k }, t)));
  clsSel.value = state.cls;
  const search = h('input', { type: 'search', placeholder: 'Filter by SKU or name', value: state.q, 'aria-label': 'Filter by SKU or name' });
  const localBox = h('input', { type: 'checkbox', checked: state.local });
  const eligibleBox = h('input', { type: 'checkbox', checked: state.eligible });
  const table = h('table', { class: 'data stack' });
  const pager = h('div', { class: 'pager' });
  append(root, h('section', { class: 'card', 'aria-label': 'Candidate pairs' }, tabs,
    h('div', { class: 'queue-controls' }, h('div', { class: 'grow' }, search), clsSel,
      h('label', { class: 'toggle-inline', title: 'Potential and conditional alternatives only' }, h('span', { class: 'switch' }, eligibleBox), 'Eligible only'),
      h('label', { class: 'toggle-inline' }, h('span', { class: 'switch' }, localBox), 'Changed in this browser')),
    h('div', { class: 'table-wrap' }, table), pager));

  clsSel.addEventListener('change', () => { state.cls = clsSel.value; state.limit = PAGE; draw(); });
  search.addEventListener('input', debounce(() => { state.q = search.value.trim(); state.limit = PAGE; draw(); }, 150));
  localBox.addEventListener('change', () => { state.local = localBox.checked; draw(); });
  eligibleBox.addEventListener('change', () => { state.eligible = eligibleBox.checked; draw(); });
  const unsubscribe = ctx.reviews.subscribe(async () => { items = await reviewQueueItems(ctx); draw(); });

  const fmtDate = (iso) => (iso ? new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' }) : '—');
  const finderLink = (it, compare) => `#/alternatives/${it.source.id}?focus=${encodeURIComponent(it.candidate.id)}${compare ? '&compare=1' : ''}`;

  function draw() {
    syncUrl();
    const q = state.q.toLowerCase();
    const base = items.filter((it) => (!state.cls || it.result.classification === state.cls)
      && (!state.local || it.review.changedLocally)
      && (!state.eligible || isEligible(it.result.classification))
      && (!q || [it.source.sku, it.source.name, it.candidate.sku, it.candidate.name].some((x) => x.toLowerCase().includes(q))));
    const counts = { all: base.length };
    for (const k of Object.keys(REVIEW_LABELS)) counts[k] = base.filter((it) => it.review.reviewStatus === k).length;

    clear(tabs);
    for (const [k, label] of [['all', 'All'], ['pending', 'Pending'], ['approved_for_demo', 'Approved for demo'], ['rejected', 'Rejected']]) {
      tabs.append(h('button', { type: 'button', role: 'tab', class: 'tab', 'aria-selected': String(state.status === k), on: { click: () => { state.status = k; state.limit = PAGE; draw(); } } },
        label, h('span', { class: 'n' }, String(counts[k]))));
    }

    const list = base.filter((it) => state.status === 'all' || it.review.reviewStatus === state.status)
      .sort((a, b) => (b.review.reviewedAt ?? '').localeCompare(a.review.reviewedAt ?? '') || a.source.sku.localeCompare(b.source.sku) || (b.result.score ?? -1) - (a.result.score ?? -1));

    clear(table);
    clear(pager);
    if (!list.length) {
      table.append(h('tbody', {}, h('tr', {}, h('td', { colspan: '8' }, emptyState({
        title: 'No pairs in this view',
        body: state.status === 'all' ? 'Adjust the filters above.' : `No pairs are “${REVIEW_LABELS[state.status]}” with these filters.`,
      })))));
      return;
    }
    table.append(h('thead', {}, h('tr', {}, ['Source', 'Candidate', 'Classification', 'Score', 'Status', 'Note', 'Reviewed', ''].map((t) =>
      h('th', { scope: 'col' }, t || h('span', { class: 'visually-hidden' }, 'Actions'))))));
    const tbody = h('tbody', {});
    for (const it of list.slice(0, state.limit)) {
      const key = pairKey(it.source.id, it.candidate.id);
      const open = state.open.has(key);
      const toggle = h('button', { type: 'button', class: 'btn btn-ghost btn-sm', 'aria-expanded': String(open), on: { click: () => { if (open) state.open.delete(key); else state.open.add(key); draw(); } } },
        open ? 'Hide' : 'Details');
      tbody.append(h('tr', { class: open ? 'is-selected' : null },
        h('td', { class: 'cell-first' }, h('div', { class: 'pair' }, h('a', { href: `#/product/${it.source.id}` }, it.source.name), skuTag(it.source.sku))),
        h('td', { 'data-label': 'Candidate' }, h('div', { class: 'pair' }, h('span', { class: 'small muted' }, '→ alternative'), h('a', { href: `#/product/${it.candidate.id}` }, it.candidate.name), skuTag(it.candidate.sku))),
        h('td', { 'data-label': 'Classification' }, classificationChip(it.result.classification)),
        h('td', { 'data-label': 'Score', class: 'num' }, typeof it.result.score === 'number' ? String(it.result.score) : h('span', { class: 'muted' }, 'withheld')),
        h('td', { 'data-label': 'Status' }, reviewChip(it.review.reviewStatus)),
        h('td', { 'data-label': 'Note', class: 'note-cell' }, it.review.reviewNote ? h('span', { class: 'clamp', title: it.review.reviewNote }, it.review.reviewNote) : h('span', { class: 'empty-note' }, 'No note')),
        h('td', { 'data-label': 'Reviewed', class: 'small muted' }, fmtDate(it.review.reviewedAt)),
        h('td', { class: 'actions' }, h('a', { class: 'btn btn-secondary btn-sm', href: finderLink(it, true) }, icon('compare'), 'Open comparison'), ' ', toggle)));
      if (open) {
        const r = it.result;
        tbody.append(h('tr', { class: 'detail-row' }, h('td', { colspan: '8' }, h('div', { class: 'detail-grid' },
          h('div', {}, h('h4', {}, 'Explanation'), h('p', {}, r.explanation)),
          h('div', {}, h('h4', {}, r.blockingReasons.length ? 'Blockers' : 'Conditions'),
            h('ul', { style: { margin: 0, paddingLeft: '18px' } }, (r.blockingReasons.length ? r.blockingReasons : r.conditions).map((t) => h('li', {}, t))),
            !r.blockingReasons.length && !r.conditions.length ? h('p', { class: 'muted' }, 'None') : null),
          h('div', {}, h('h4', {}, 'Note'), h('p', {}, it.review.reviewNote ?? 'No note yet.'),
            h('p', { class: 'small muted', style: { marginTop: '6px' } }, it.seed ? 'Seeded by the demo generator' : 'Added from a live search in this browser',
              it.review.changedLocally ? ' · changed locally' : ''),
            h('a', { href: finderLink(it, false), style: { display: 'inline-block', marginTop: '8px' } }, 'Review in the finder →'))))));
      }
    }
    table.append(tbody);
    pager.append(h('span', {}, `Showing ${Math.min(state.limit, list.length)} of ${list.length} pairs`));
    if (list.length > state.limit) pager.append(h('button', { type: 'button', class: 'btn btn-secondary btn-sm', on: { click: () => { state.limit = Infinity; draw(); } } }, `Show all ${list.length}`));
  }

  draw();
  return unsubscribe;
}

